def verify_anchor_against_exe():
    """Byte-verify the primary anchor against the reconstituted EXE (soft)."""
    exe = os.path.join(ROOT, 'raw', 'COLONIZE', 'VICEROY.EXE')
    want = bytes(int(b, 16) for b in ANCHOR_AOB.split())
    if not os.path.exists(exe):
        print('note: raw/COLONIZE/VICEROY.EXE not present (run bin/reconstitute.py) — '
              'skipping generation-time anchor byte-check')
        return
    data = open(exe, 'rb').read()
    got = data[DGROUP_FILE_BASE + ANCHOR_OFF: DGROUP_FILE_BASE + ANCHOR_OFF + len(want)]
    if got != want:
        sys.exit(f'ANCHOR MISMATCH vs VICEROY.EXE @0x{DGROUP_FILE_BASE + ANCHOR_OFF:X}: {got!r}')
    if data.count(want) != 1:
        sys.exit('ANCHOR NOT UNIQUE in VICEROY.EXE')
    print(f'anchor byte-check OK (file 0x{DGROUP_FILE_BASE + ANCHOR_OFF:05X}, unique in EXE)')


