        if t.startswith('aob:'):
            return aob_entry(d, addr, int(t[4:]))
        if t in ELEM:
            return field_entries('DG', [dict(g, off=int(g['off'], 16))])[0]
        if t == 'fptr':
            off = int(g['off'], 16)
            kids = [scalar_entry('offset', f'DG+{off:X}', 'u16', True),
                    scalar_entry('segment', f'DG+{off + 2:X}', 'u16', True)]
            return entry(d, children=kids)
