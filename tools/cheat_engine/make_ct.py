ROOT = os.path.dirname(os.path.dirname(HERE))
INV = json.load(open(os.path.join(HERE, 'addresses.json')))

DGROUP_FILE_BASE = int(INV['anchors']['dgroup_file_base'], 16)
ANCHOR_AOB = INV['anchors']['primary']['bytes_hex']
ANCHOR_OFF = int(INV['anchors']['primary']['dgroup_off'], 16)
ANCHOR2_OFF = int(INV['anchors']['secondary']['dgroup_off'], 16)
