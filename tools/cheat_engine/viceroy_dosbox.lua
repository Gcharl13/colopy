function V.recruits()
  for i = 0, 2 do
    local b = V.DG + OFF.recruit + i * 6
    print(('dock slot %d: type=%s cost=%s'):format(i, r8(b), r16(b + 4)))
  end
end

-- ---------------------------------------------------------------- cheats
function V.setGold(amount, power)
  local b = V.DG + OFF.power_base + (power or (r16(V.DG + OFF.curplayer) or 0)) * OFF.power_stride
  writeInteger(b + 0x2A, amount)
  print(('gold[%s] = %d'):format(POWERS[((power or 0) % 12) + 1], amount))
end

function V.revealMap(power)
  power = power or (r16(V.DG + OFF.curplayer) or 0)
  local plane, w, h = V.readPlane(3)
  if not plane then print('fog plane unavailable') return end
  local bit = 2 ^ (4 + power)
  for i = 1, w * h do
    local v = plane[i]
    if math.floor(v / bit) % 2 == 0 then plane[i] = v + bit end
  end
  writeBytes(V.planeAddr(3), plane)
  print(('map revealed for %s (fog plane OR 0x%02X)'):format(POWERS[power + 1], bit))
end

