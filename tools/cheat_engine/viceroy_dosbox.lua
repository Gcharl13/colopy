local function r8(a)  return readBytes(a, 1) end
local function r16(a) return readSmallInteger(a) end
local function r32(a) return readInteger(a) end
local function s16(v) if v and v >= 0x8000 then return v - 0x10000 end return v end
local function s32(v) if v and v >= 0x80000000 then return v - 0x100000000 end return v end

-- ---------------------------------------------------------------- attach
function V.attach()
  if getOpenedProcessID() ~= 0 and getOpenedProcessID() ~= nil then return true end
  for _, n in ipairs(V.PROCS) do
    local pid = getProcessIDFromProcessName(n)
    if pid then openProcess(pid); print(('VICEROY: attached to %s (pid %d)'):format(n, pid)); return true end
  end
  print('VICEROY: no DOSBox process found — start the game, then File>Open Process, then VICEROY.locate()')
  return false
end

-- ---------------------------------------------------------------- locate
local function validMemBase(mb)
  if mb < 0 then return false end
  if r16(mb + 0x413) ~= 640 then return false end   -- BIOS Data Area: base memory KB
  local int21 = r32(mb + 0x84)                      -- IVT: INT 21h vector populated
  local int08 = r32(mb + 0x20)                      -- IVT: INT 08h (timer) populated
  return int21 ~= nil and int21 ~= 0 and int08 ~= nil and int08 ~= 0
end

function V.findMemBase(dg)
  -- Walk DGROUP-segment candidates high->low: candidates ascend from below,
  -- so the FIRST readable+valid one is the lowest = true phys 0. The host
  -- allocation base is deliberately NOT trusted (DOSBox 0.74-3 Linux places
  -- phys 0 at allocation+0x10); the BDA+IVT signature was verified unique
  -- across the whole space in the live session (README §Verification).
  for seg = 0xA000, 0, -1 do
    local mb = dg - seg * 16
    if mb >= 0 and validMemBase(mb) then return mb end
  end
  return nil
end

function V.locate()
  if not V.attach() then return false end
  local res = AOBScan(V.ANCHOR_AOB, '+W')
  if res == nil or res.Count == 0 then
    if res then res.destroy() end
    res = AOBScan(V.ANCHOR_AOB)
  end
  if res == nil or res.Count == 0 then
    print('VICEROY: DGROUP anchor not found — is VICEROY.EXE actually running inside DOSBox?')
    if res then res.destroy() end
    return false
  end
  local best, bestSec = nil, false
  for i = 0, res.Count - 1 do
    local dg = tonumber(res[i], 16) - V.ANCHOR_OFF
    local sec = readString(dg + V.ANCHOR2_OFF, 13, false) == V.ANCHOR2_STR
    if sec then best, bestSec = dg, true break end
    if best == nil then best = dg end
  end
  res.destroy()
  V.DG = best
  V.MB = V.findMemBase(V.DG)
  if V.MB == nil then
    print('VICEROY: WARNING — MemBase (phys 0) not validated; far pointers (map planes) unavailable.')
  end
  pcall(unregisterSymbol, 'DG'); registerSymbol('DG', V.DG, true)
  if V.MB then pcall(unregisterSymbol, 'MB'); registerSymbol('MB', V.MB, true) end
  V.refresh()
  if V.timer == nil then
    V.timer = createTimer(getMainForm())
    V.timer.Interval = 400
    V.timer.OnTimer = function() if V.DG then pcall(V.refresh) end end
  end
  V.timer.Enabled = true
  print(('VICEROY: DGROUP = %X (seg %04X)%s'):format(V.DG,
    V.MB and math.floor((V.DG - V.MB) / 16) or 0,
    V.MB and (' , MemBase = %X'):format(V.MB) or ''))
  print(('VICEROY: secondary anchor (@ORDERS letters at DG+54DE): %s'):format(
    bestSec and 'OK' or 'not present (pre-boot state?) — proceeding on primary anchor'))
  V.status()
  return true
end

function V.stop()
  if V.timer then V.timer.Enabled = false end
end

-- dynamic symbols: near pointers + far map-plane pointers
local LAYERSYM = {'MAPTERRAIN', 'MAPLAYER1', 'MAPLAYER2', 'MAPFOG'}
function V.refresh()
  local dg = V.DG
  if not dg then return end
  local function nreg(sym, off)
    local p = r16(dg + off)
    pcall(unregisterSymbol, sym)
    registerSymbol(sym, dg + (p or 0), true)
  end
  nreg('CURPOWER', OFF.curpower)
  nreg('CURCOLONY', OFF.curcolony)
  nreg('CURTRIBE', OFF.curtribe)
  if V.MB then
    for i, sym in ipairs(LAYERSYM) do
      local base = OFF.layer[i]
      local o, s = r16(dg + base), r16(dg + base + 2)
      pcall(unregisterSymbol, sym)
      registerSymbol(sym, V.MB + (s or 0) * 16 + (o or 0), true)
    end
  end
end

-- ---------------------------------------------------------------- map access
function V.mapDims()
  return r16(V.DG + OFF.mapw) or 0, r16(V.DG + OFF.maph) or 0
end

function V.planeAddr(n) -- n = 0..3
  local base = OFF.layer[n + 1]
  local o, s = r16(V.DG + base), r16(V.DG + base + 2)
  if not o or not s or not V.MB then return nil end
  return V.MB + s * 16 + o
end

function V.readPlane(n)
  local w, h = V.mapDims()
  local a = V.planeAddr(n)
  if not a or w == 0 then return nil end
  return readBytes(a, w * h, true), w, h
end

-- record/HUD coords -> plane index. Direct indexing is correct (live-verified);
-- V.shift stays (0,0) unless V.calibrate() finds otherwise (diagnostic only —
-- a nonzero result usually means MemBase went wrong, not the map).
function V.tileIndex(x, y)
  local w, h = V.mapDims()
  return ((y + V.shift.dy) % h) * w + ((x + V.shift.dx) % w)
end

function V.tile(x, y)
  local a = V.planeAddr(0)
  if not a then print('map planes unavailable') return end
  local raw = r8(a + V.tileIndex(x, y))
  if not raw then return end
  local id = raw % 32
  local fold = id
  if id >= 8 and id <= 23 then fold = (id % 8) + 8 end   -- auto-forest fold (hard rule 3)
  local name = TERRAIN[fold] or ('id ' .. fold)
  local special = (math.floor(raw / 32) % 2) == 1
  local bit6 = (math.floor(raw / 64) % 2) == 1
  local bit7 = (math.floor(raw / 128) % 2) == 1
  -- per-terrain stats from the runtime table (NAMES-loaded)
  local t = V.DG + OFF.terr_base + fold * OFF.terr_stride
  print(('tile(%d,%d): raw=0x%02X id=%d %s%s%s%s | move=%s def=%s improve=%s value=%s'):format(
    x, y, raw, fold, name,
    special and ' +special(0x20)' or '', bit6 and ' +bit6' or '', bit7 and ' +bit7' or '',
    tostring(r8(t)), tostring(r8(t + 1)), tostring(r8(t + 2)), tostring(r8(t + 3))))
  return raw
end

-- Diagnostic: best-fit a (dx,dy) plane shift from live colonies/settlements/
-- ships. Expected result is (0,0); anything else indicates a broken MemBase
-- (see README §MemBase pitfall) or an unknown DOSBox memory layout.
function V.calibrate()
  local plane, w, h = V.readPlane(0)
  if not plane then print('calibrate: map planes unavailable') return end
  local anchors = {}   -- {x, y, wantWater}
  local dg = V.DG
  local nc = r16(dg + OFF.colonycount) or 0
  for i = 0, math.min(nc, 50) - 1 do
    local b = dg + OFF.colony_base + i * OFF.colony_stride
    local x, y = r8(b), r8(b + 1)
    if x and x < w and y < h and (r8(b + 2) or 0) ~= 0 then anchors[#anchors + 1] = {x, y, false} end
  end
  for i = 0, 59 do
    local b = dg + OFF.settle_base + i * OFF.settle_stride
    local x, y = r8(b), r8(b + 1)
    if not x or (x == 0 and y == 0) then break end
    if x < w and y < h then anchors[#anchors + 1] = {x, y, false} end
  end
  local nu = r16(dg + OFF.unitcount) or 0
  for i = 0, math.min(nu, 300) - 1 do
    local b = dg + OFF.unit_base + i * OFF.unit_stride
    local x, y, t = r8(b), r8(b + 1), r8(b + 2)
    if x and x < w and y < h and t and t >= 0x0D and t <= 0x12 then
      anchors[#anchors + 1] = {x, y, true}     -- naval unit -> water tile
    end
  end
  if #anchors < 5 then print('calibrate: too few anchors (' .. #anchors .. ')') return end
  local best, bx, by = -1, 0, 0
  for dy = 0, h - 1 do
    for dx = 0, w - 1 do
      local score = 0
      for _, an in ipairs(anchors) do
        local id = plane[((an[2] + dy) % h) * w + ((an[1] + dx) % w) + 1] % 32
        local water = (id == 25 or id == 26 or id == 27)
        if water == an[3] then score = score + 1 end
      end
      if score > best then best, bx, by = score, dx, dy end
    end
  end
  local pct = math.floor(100 * best / #anchors)
  V.shift.dx, V.shift.dy, V.shift.calibrated = bx, by, pct >= 85
  print(('calibrate: shift=(%d,%d) fits %d/%d anchors (%d%%)%s'):format(
    bx, by, best, #anchors, pct,
    pct >= 85 and '' or ' — LOW CONFIDENCE, shift left as best guess'))
  return bx, by, pct
end

-- ---------------------------------------------------------------- dumps
function V.status()
  local dg = V.DG
  if not dg then print('not located — run VICEROY.locate()') return end
  local w, h = V.mapDims()
  print(('year %s (turn %s, season %s) | difficulty %s | player %s | units %s | colonies %s | map %dx%d'):
    format(r16(dg + OFF.year), r16(dg + OFF.turn), r16(dg + OFF.season),
           r8(dg + OFF.difficulty), POWERS[(r16(dg + OFF.curplayer) or 0) + 1],
           r16(dg + OFF.unitcount), r16(dg + OFF.colonycount), w, h))
  print(('REF: %s regulars, %s cavalry, %s man-o-war, %s artillery | SoL meter %s'):
    format(r16(dg + OFF.ref), r16(dg + OFF.ref + 2), r16(dg + OFF.ref + 4),
           r16(dg + OFF.ref + 6), s16(r16(dg + 0x53D0))))
end

function V.powers()
  for i = 0, 3 do
    local b = V.DG + OFF.power_base + i * OFF.power_stride
    print(('%-11s tax=%s%% rebel=%s%% gold=%s bells=%s(+%s/t) crosses=%s/%s ff=%s royal=%s boycott=0x%04X'):
      format(POWERS[i + 1], r8(b + 1), r8(b + 2), r32(b + 0x2A), r16(b + 0x0C), r16(b + 0x0E),
             r16(b + 0x2E), r16(b + 0x30), r16(b + 0x14), s32(r32(b + 0x22)), r16(b + 0x20) or 0))
    print(('            prices: %s'):format(table.concat((function()
      local t = {} for g = 0, 15 do t[#t + 1] = GOODS[g + 1] .. '=' .. tostring(r8(b + 0x4C + g)) end return t
    end)(), ' ')))
  end
end

function V.colonies()
  local n = r16(V.DG + OFF.colonycount) or 0
  print(('%d colonies:'):format(n))
  for i = 0, 49 do
    local b = V.DG + OFF.colony_base + i * OFF.colony_stride
    local name = readString(b + 2, 24, false)
    if name and #name > 0 then
      print(('[%2d] %-16s (%2s,%2s) %-11s size=%s hammers=%s bank=%s target=%s SoL=%s/%s'):
        format(i, name, r8(b), r8(b + 1), POWERS[(r8(b + 0x1A) or 0) + 1], r8(b + 0x1F),
               r16(b + 0x92), r16(b + 0xB6), r8(b + 0x94), s32(r32(b + 0xC2)), s32(r32(b + 0xC6))))
      local t = {}
      for g = 0, 15 do local v = r16(b + 0x9A + g * 2) or 0
        if v > 0 then t[#t + 1] = GOODS[g + 1] .. '=' .. v end end
      if #t > 0 then print('      stock: ' .. table.concat(t, ' ')) end
    end
  end
end

function V.units(nmax)
  local n = math.min(r16(V.DG + OFF.unitcount) or 0, nmax or 40)
  for i = 0, n - 1 do
    local b = V.DG + OFF.unit_base + i * OFF.unit_stride
    local t, of = r8(b + 2) or 0, r8(b + 3) or 0
    print(('[%3d] %-13s (%2s,%2s) %-11s order=%-11s goto=(%s,%s) moves=%s tools=%s ai=%s'):
      format(i, UNITS[t + 1] or ('type ' .. t), r8(b), r8(b + 1),
             POWERS[(of % 16) + 1] or of, ORDERS[(r8(b + 8) or 0) + 1] or '?',
             r8(b + 9), r8(b + 10), r8(b + 5), r8(b + 0x15),
             string.char(math.max(32, math.min(126, r8(b + 7) or 32)))))
  end
end

function V.settlements()
  for i = 0, 59 do
    local b = V.DG + OFF.settle_base + i * OFF.settle_stride
    local x, y = r8(b), r8(b + 1)
    if not x or (x == 0 and y == 0) then break end
    local fl, mi = r8(b + 3) or 0, r8(b + 5) or 0
    print(('[%2d] (%2d,%2d) %-9s pop=%-2s %s%s'):format(i, x, y,
      POWERS[(r8(b + 2) or 0) + 1] or '?', r8(b + 4),
      (fl % 8 >= 4) and 'CAPITAL ' or '',
      mi ~= 0xFF and ('mission=' .. (POWERS[(mi % 16) + 1] or mi)) or ''))
  end
end

function V.unitStats()
  for i = 0, 22 do
