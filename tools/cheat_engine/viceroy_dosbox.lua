--[[
VICEROY (Sid Meier's Colonization, 1994 DOS) <-> DOSBox live-memory bridge
Generated by tools/cheat_engine/make_ct.py — do not hand-edit; edit the
generator / addresses.json instead.

How it works (see tools/cheat_engine/README.md for the full story):
 * DOSBox keeps emulated DOS RAM as one big host allocation; emulated physical
   address P sits at (MemBase + P).
 * The game's data segment (DGROUP) is found by scanning for the static
   section-name table "UNIT\0ORDERS\0ACTIONS\0" that lives at DGROUP:0x2258
   (unique in the EXE and in live RAM — docs/RUNTIME_SNAPSHOT.md).
 * MemBase (emulated phys 0) is recovered by walking DGROUP-segment candidates
   from high to low and accepting the first address whose BIOS Data Area checks
   out (u16[0x413] == 640 KB plus populated INT 08h/21h vectors). Do NOT assume
   the host allocation base is phys 0 — DOSBox 0.74-3 (Linux) puts phys 0 at
   allocation+0x10, which silently shifts every far-pointer read by 16 bytes.
   The BDA signature is unique in the whole address space (verified live).
 * DGROUP:0xNNNN citations from the repo specs are then readable at DG+0xNNNN,
   exactly as tools/runtime_snapshot.py does it headlessly.

Registered symbols (usable in any address field once located):
  DG          DGROUP linear base
  MB          emulated physical 0 (MemBase)
  CURPOWER    active PowerRecord      = DG + [DG+0x84FC]
  CURCOLONY   active ColonyRecord     = DG + [DG+0x8542]
  CURTRIBE    active TribeData record = DG + [DG+0x8D4E]
  MAPTERRAIN / MAPLAYER1 / MAPLAYER2 / MAPFOG
              linear addresses of the four map byte-planes (far ptrs at
              DGROUP:0x15C/0x160/0x164/0x168)

Console quick start:
  VICEROY.locate()      -- attach + find everything (the table auto-runs this)
  VICEROY.status()      -- one-screen game-state summary
  VICEROY.powers()      -- the four PowerRecords
  VICEROY.colonies()    -- every colony slot in use
  VICEROY.units(20)     -- first 20 unit records
  VICEROY.settlements() -- native settlements
  VICEROY.calibrate()   -- diagnostic: verify plane indexing (expect shift (0,0))
  VICEROY.tile(x, y)    -- decode the terrain under record/HUD coords
  VICEROY.revealMap(0)  -- CHEAT: reveal the map for power 0 (England)
]]

