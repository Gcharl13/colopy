    print(('%-13s move(x3)=%s att=%s def=%s cargo=%s hull=%s guns=%s'):
      format(UNITS[i + 1], r8(b + 4), r8(b + 6), r8(b + 5), r8(b + 7), r8(b + 9), r8(b + 11)))
  end
