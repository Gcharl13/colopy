#!/usr/bin/env python3
"""Generate the Arduino-IDE sketch folder for the Teensy 4.1 build.

The Arduino IDE only compiles sources INSIDE the sketch folder and
passes no -I/-D flags, so the PlatformIO layout (cport/teensy/ +
build_src_filter over ../core etc.) cannot be opened directly.  This
tool flattens everything into cport/arduino/colopy/:

  * copies every needed .c/.h from core/, data/, render/, game/,
    rewriting the cross-directory includes ("../core/colopy_sim.h" ->
    "colopy_sim.h" -- all project headers have unique basenames, which
    this tool asserts);
  * emits colopy.ino = a build-config banner (the defines PlatformIO
    would pass with -D) + the verbatim cport/teensy/colopy_teensy.ino;
  * writes the sketch-local README.md with the IDE steps.

Re-run after pulling engine changes; the copies are generated output
(do not edit them in place).  Run from the repo root:

    python3 tools/gen_arduino_sketch.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "cport" / "arduino" / "colopy"

SOURCES = [
    "cport/core/*.c", "cport/core/*.h",
    "cport/data/colopy_data.c", "cport/data/colopy_data.h",
    "cport/data/colopy_text.c", "cport/data/colopy_text.h",
    "cport/data/colopy_ui.c", "cport/data/colopy_ui.h",
    "cport/data/colopy_pak.h",
    "cport/render/*.c", "cport/render/*.h",
    "cport/game/*.c", "cport/game/*.h",
]

INO_SRC = ROOT / "cport" / "teensy" / "colopy_teensy.ino"

CONFIG = """\
/* ==== Arduino IDE build config (generated: tools/gen_arduino_sketch.py)
 *
 * The IDE passes no -D flags, so the switches PlatformIO's
 * platformio.ini would set live HERE.  Everything below this banner is
 * the verbatim cport/teensy/colopy_teensy.ino; the .c/.h files beside
 * it are flattened copies of cport/{core,data,render,game} -- regenerate
 * with the tool after pulling engine changes, do not edit them here.
 *
 * Display + USB-keyboard build (the game): needs the ILI9341_t3n
 * library (github.com/KurtE/ILI9341_t3n -> Sketch > Include Library >
 * Add .ZIP Library), a Teensy 4.1 WITH the PSRAM soldered (the pak
 * buffer is EXTMEM), and USBHost_t36 + SD + SPI (all ship with
 * Teensyduino).  For the serial-only digest shell, comment BOTH
 * defines out -- no display library or PSRAM needed.
 *
 * TFT pins default to CS 10 / DC 9 (MOSI 11 / MISO 12 / SCK 13 =
 * SPI0); if rewired, define COLOPY_TFT_CS / COLOPY_TFT_DC here before
 * the include block. */
#define COLOPY_ILI9341 1
#define COLOPY_USBHOST 1

"""

README = """\
# Colopy — Arduino IDE sketch (Teensy 4.1)

GENERATED by `tools/gen_arduino_sketch.py` — do not edit the copied
`.c`/`.h` files here; change the originals under `cport/` and re-run
the tool.  Build config (display / USB keyboard on-off, TFT pins) is
the banner at the top of `colopy.ino`.

## Steps

1. Install [Teensyduino](https://www.pjrc.com/teensy/td_download.html)
   (Arduino IDE 2.x: add the Teensy boards URL in Preferences, then
   Boards Manager -> "Teensy").
2. Display build only: install the `ILI9341_t3n` library — download the
   ZIP from <https://github.com/KurtE/ILI9341_t3n> and use
   Sketch > Include Library > Add .ZIP Library.  (`SD`, `SPI`,
   `USBHost_t36` ship with Teensyduino.)
3. Open `colopy.ino`.  Tools menu: Board **Teensy 4.1**, USB Type
   **Serial** (the USB keyboard goes on the separate HOST port header),
   CPU Speed 600 MHz, Optimize "Faster".
4. microSD (FAT32, files in the card ROOT — the sketch opens them by
   bare name): both files are generated, git-ignored output — build
   them from the repo root with

       pip install pillow               # once (gen_sd_pack's asset census)
       python3 bin/reconstitute.py      # -> raw/COLONIZE/*.SAV
       python3 tools/gen_sd_pack.py     # -> cport/pak/COLOPY.PAK
                                        #    (auto-builds port/assets/
                                        #    manifest.json on first run)

   then copy `cport/pak/COLOPY.PAK` and `raw/COLONIZE/COLONY00.SAV`
   onto the card.
5. Flash, open Serial Monitor at 115200 baud:

       l COLONY00.SAV      load
       v                   draw the map view once (display build)
       g                   game loop (USB keyboard, or `k <name>` over
                           serial: `k Space`, `k ArrowUp`, `k !g` = Alt+G)
       t 100               run 100 turns, one digest line per turn
       d / i / s OUT.SAV   digest / overview / save back to SD

The digests from `t 100` must match a host run
(`cport/host/smoke --saveout <fixture> 100 out.sav`) turn for turn —
that is the hardware acceptance test.  The wiring/bring-up checklist
lives in `cport/teensy/README.md`.
"""

INCLUDE_RE = re.compile(r'(#include\s+")(?:\.\./)+[a-z]+/(colopy_\w+\.h)(")')


def main():
    files = []
    for pat in SOURCES:
        got = sorted(ROOT.glob(pat))
        if not got:
            sys.exit(f"no sources match {pat} (run from a full checkout)")
        files += [p for p in got if p.suffix in (".c", ".h")]
    names = [p.name for p in files]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        sys.exit(f"basename collision across dirs: {sorted(dupes)} — "
                 "the flat-include rewrite would be ambiguous")

    DEST.mkdir(parents=True, exist_ok=True)
    for stale in list(DEST.glob("*.c")) + list(DEST.glob("*.h")) + \
                 list(DEST.glob("*.ino")):
        stale.unlink()

    for p in files:
        text = p.read_text()
        text, n = INCLUDE_RE.subn(r"\1\2\3", text)
        (DEST / p.name).write_text(text)

    (DEST / "colopy.ino").write_text(CONFIG + INO_SRC.read_text())
    (DEST / "README.md").write_text(README)
    print(f"wrote {len(files) + 1} sources + README to "
          f"{DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
