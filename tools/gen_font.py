def row_to_byte(row):
    b = 0
    for i, c in enumerate(row[:8]):
        if c == "#":
            b |= (1 << i)
    return b


def main():
    box = ("########", "#......#", "#......#", "#......#",
           "#......#", "#......#", "########", "........")
    lines = [
        "/* font8x8.h — generated by tools/gen_font.py. 8x8 bitmap font for",
        " * ASCII 0x20..0x7E. Bit 0 (LSB) is the leftmost pixel of each row. */",
        "#ifndef MPEDIT_FONT8X8_H",
        "#define MPEDIT_FONT8X8_H",
        "#include <stdint.h>",
        "#define FONT_FIRST 0x20",
        "#define FONT_LAST  0x7E",
        "static const uint8_t FONT8X8[0x7E - 0x20 + 1][8] = {",
    ]
    for code in range(0x20, 0x7F):
        ch = chr(code)
        rows = G.get(ch, box)
        bytes_ = ", ".join(f"0x{row_to_byte(r):02X}" for r in rows)
        lines.append(f"    {{ {bytes_} }},  /* 0x{code:02X} {ch!r} */")
    lines.append("};")
    lines.append("#endif")
    out = ROOT / "mapedit_modern" / "include" / "font8x8.h"
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out} ({len(G)} authored glyphs)")


if __name__ == "__main__":
    main()
