#!/usr/bin/env python3
# generate_manifest.py
#
# Walks reverse_engineered/raw/COLONIZE and emits MANIFEST.md at the
# reverse_engineered/ root. For every file we record:
#   - relative path
#   - size in bytes
#   - SHA256 hash
#   - magic bytes (first 16 bytes, hex)
#   - extension
#
# This is the canonical filesystem-level inventory of the DOS distribution.
# It does NOT decode formats; it only catalogs.

import hashlib
import os
import sys
from pathlib import Path


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def magic_of(path: Path, n: int = 16) -> str:
    with path.open("rb") as f:
        head = f.read(n)
    return head.hex().upper()


def is_foreign(name: str) -> bool:
    """True if the file in COLONIZE/ is *not* an original DOS-distribution
    file but a leftover artifact from prior extraction work. These files
    must stay in the inventory but be flagged so they don't contaminate
    counts of what the original game shipped with."""
    n = name.upper()
    # PNG, JSON, and .part shards generated by previous TERRAIN.SS extraction.
    if n.startswith("TERRAIN.SS.") and (
        n.endswith(".PNG") or n.endswith(".JSON") or n.endswith(".PART")
    ):
        return True
    # Bare TERRAIN.SS.json (top-level metadata from prior tooling).
    if n == "TERRAIN.SS.JSON":
        return True
    return False


def main():
    root = Path(__file__).resolve().parent.parent
    raw = root / "raw" / "COLONIZE"
    if not raw.is_dir():
        print(f"ERROR: {raw} not found", file=sys.stderr)
        sys.exit(1)

    files = sorted(p for p in raw.iterdir() if p.is_file())

    rows = []
    for p in files:
        rows.append(
            {
                "name": p.name,
                "ext": p.suffix.upper().lstrip("."),
                "size": p.stat().st_size,
                "sha256": sha256_of(p),
                "magic": magic_of(p, 16),
                "foreign": is_foreign(p.name),
            }
        )

    originals = [r for r in rows if not r["foreign"]]
    foreigners = [r for r in rows if r["foreign"]]

    by_ext: dict[str, list] = {}
    for r in originals:
        by_ext.setdefault(r["ext"] or "(none)", []).append(r)

    out = root / "MANIFEST.md"
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# COLONIZE/ Manifest\n\n")
        f.write(
            "Filesystem-level inventory of the original DOS distribution. "
            "Generated by `tools/generate_manifest.py`. Do not hand-edit; "
            "rerun the tool to refresh.\n\n"
        )
        f.write(
            f"Total files in `raw/COLONIZE/`: **{len(rows)}** "
            f"(originals: **{len(originals)}**, foreign/derived: **{len(foreigners)}**)\n\n"
        )
        f.write(
            "Source: `reverse_engineered/raw/COLONIZE/` "
            "(bit-for-bit copy of `COLONIZE/`).\n\n"
        )
        f.write(
            "**Foreign files** are leftover artifacts from prior extraction work "
            "that wound up in the original COLONIZE/ folder. They are catalogued "
            "below for transparency but are excluded from the per-extension counts "
            "and from the disassembly / decoding pipeline.\n\n"
        )

        f.write("## Counts by extension (originals only)\n\n")
        f.write("| Ext | Count | Total bytes |\n")
        f.write("|-----|------:|------------:|\n")
        for ext in sorted(by_ext):
            total = sum(r["size"] for r in by_ext[ext])
            f.write(f"| `{ext}` | {len(by_ext[ext])} | {total:,} |\n")
        f.write("\n")

        f.write("## Files by extension (originals)\n\n")
        for ext in sorted(by_ext):
            f.write(f"### `.{ext}` ({len(by_ext[ext])} files)\n\n")
            f.write("| Name | Size | SHA256 | Magic (first 16 bytes) |\n")
            f.write("|------|-----:|--------|------------------------|\n")
            for r in sorted(by_ext[ext], key=lambda x: x["name"]):
                f.write(
                    f"| `{r['name']}` | {r['size']:,} | `{r['sha256'][:16]}…` | `{r['magic']}` |\n"
                )
            f.write("\n")

        if foreigners:
            f.write("## Foreign / derived files (excluded from counts)\n\n")
            f.write(
                "These files are present in `raw/COLONIZE/` but were created "
                "by prior extraction tooling, not shipped with the original "
                "DOS game. Listed here so the inventory is complete.\n\n"
            )
            f.write("| Name | Size | SHA256 |\n")
            f.write("|------|-----:|--------|\n")
            for r in sorted(foreigners, key=lambda x: x["name"]):
                f.write(f"| `{r['name']}` | {r['size']:,} | `{r['sha256'][:16]}…` |\n")
            f.write("\n")

    json_out = root / "MANIFEST.json"
    import json
    with json_out.open("w", encoding="utf-8", newline="\n") as f:
        json.dump(rows, f, indent=2)

    print(f"wrote {out} ({len(rows)} files)")
    print(f"wrote {json_out}")


if __name__ == "__main__":
    main()
